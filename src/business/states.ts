/** Ray casting; the polygons are small (40 and ~300 points), so this is microseconds. */
function inside(point: LatLng, poly: [number, number][]): boolean {
  let hit = false;
  for (let i = 0, j = poly.length - 1; i < poly.length; j = i++) {
    const [yi, xi] = poly[i]!;
    const [yj, xj] = poly[j]!;
    if (yi > point.lat !== yj > point.lat && point.lng < ((xj - xi) * (point.lat - yi)) / (yj - yi) + xi) hit = !hit;
  }
  return hit;
}

/** Which service state a point is in, or null when it is outside both. */
export function stateOf(point: LatLng): ServiceState | null {
  for (const code of SERVICE_STATE_CODES) if (inside(point, BOUNDARIES[code])) return code;
  return null;
}
